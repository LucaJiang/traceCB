def _grid_values(args: argparse.Namespace, name: str) -> list:
    value = getattr(args, name)
    if value is None:
        return []
    if isinstance(value, list):
        return value
    if isinstance(value, tuple):
        return list(value)
    return [value]


def _has_explicit_multi_grid(args: argparse.Namespace) -> bool:
    return any(len(_grid_values(args, name)) > 1 for name in GRID_PARAMETER_NAMES)


def finalize_parsed_args(args: argparse.Namespace) -> argparse.Namespace:
    grid_requested = bool(
        args.run_prefix or args.dry_run or _has_explicit_multi_grid(args)
    )
    value_defaults = MIXTURE_GRID_DEFAULTS if grid_requested else SINGLE_GRID_DEFAULTS
    for name, default in value_defaults.items():
        if getattr(args, name) is None:
            setattr(args, name, list(default))

    if grid_requested:
        for name, default in MIXTURE_INPUT_DEFAULTS.items():
            if getattr(args, name) is None:
                setattr(args, name, default)
    if args.out_dir is None:
        args.out_dir = (
            "bench/result/chr22_eqtl_mixture" if grid_requested else "bench/result"
        )
    if args.max_snps_per_gene is None:
        args.max_snps_per_gene = 0 if grid_requested else 1000
    if args.estimate_omega is None:
        args.estimate_omega = grid_requested
    return args


